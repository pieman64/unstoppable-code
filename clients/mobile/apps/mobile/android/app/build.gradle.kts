import java.io.FileInputStream
import java.util.Properties

plugins {
    id("com.android.application")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
    // Reads google-services.json (gitignored; see google-services.json.example)
    // and generates the Firebase config consumed by firebase_core at runtime.
    id("com.google.gms.google-services") apply false
    // Uploads the Crashlytics mapping file so release stack traces deobfuscate.
    id("com.google.firebase.crashlytics") apply false
}

// Both plugins are gated on the same file: without a Firebase project config
// google-services has nothing to generate, and the Crashlytics plugin fails
// outright. Absence therefore just yields a build with no Firebase at all,
// which main.dart already tolerates.
val googleServicesFile = layout.projectDirectory.file("google-services.json")
if (googleServicesFile.asFile.exists()) {
    apply(plugin = "com.google.gms.google-services")
    apply(plugin = "com.google.firebase.crashlytics")
}

// Brand values generated by `pnpm run brand:generate-mobile`. The OAuth callback
// scheme is injected as a manifestPlaceholder so the flutter_web_auth_2 intent
// filter (AndroidManifest.xml) is brand-driven rather than hard-coded.
val brandProperties = Properties().apply {
    val file = rootProject.file("brand.properties")
    if (file.exists()) {
        FileInputStream(file).use { load(it) }
    }
}
val oauthCallbackScheme: String =
    brandProperties.getProperty("oauthCallbackScheme") ?: "canopy"

// Release signing material is sourced from android/key.properties, which is
// gitignored so keystore credentials never land in source control. CI and local
// release builds provide it; when it is absent (day-to-day dev, PR CI) the
// release build falls back to debug signing so `flutter run --release` still
// works. A debug-signed build is never suitable for distribution.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("key.properties")
    if (file.exists()) {
        FileInputStream(file).use { load(it) }
    }
}
val hasReleaseKeystore = keystoreProperties.getProperty("storeFile") != null

android {
    namespace = "com.unstoppabledomains.canopy"
    compileSdk = flutter.compileSdkVersion
    ndkVersion = flutter.ndkVersion

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    defaultConfig {
        applicationId = "com.example.unstoppablecode"
        // You can update the following values to match your application needs.
        // For more information, see: https://flutter.dev/to/review-gradle-config.
        minSdk = flutter.minSdkVersion
        targetSdk = flutter.targetSdkVersion
        versionCode = flutter.versionCode
        versionName = flutter.versionName
        manifestPlaceholders["oauthCallbackScheme"] = oauthCallbackScheme
    }

    signingConfigs {
        // Only define the release config when a keystore is actually
        // configured; otherwise the release build uses the debug config below.
        val storeFilePath = keystoreProperties.getProperty("storeFile")
        if (storeFilePath != null) {
            create("release") {
                storeFile = file(storeFilePath)
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // Prefer the real release keystore when configured (see key.properties
            // above); fall back to debug signing only for local
            // `flutter run --release`. Debug-signed artifacts must not be shipped.
            signingConfig =
                signingConfigs.getByName(if (hasReleaseKeystore) "release" else "debug")
        }
    }
}

dependencies {
    // MainActivity queries CustomTabsClient.isAuthTabSupported to decide whether
    // the OAuth callback can be the claimed HTTPS App Link. This arrives
    // transitively through flutter_web_auth_2 too, but the app compiles against
    // it directly, so it is declared directly.
    implementation("androidx.browser:browser:1.9.0")
}

kotlin {
    compilerOptions {
        jvmTarget = org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17
    }
}

flutter {
    source = "../.."
}
