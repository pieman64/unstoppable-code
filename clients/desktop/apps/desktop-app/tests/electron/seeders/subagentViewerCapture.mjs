/**
 * Seed a fake parent chat with retained managed-delegation transcript data.
 * The same local state is suitable for an Electron or Portal capture: it
 * creates no provider process or mock-server scenario.
 *
 * @param {object} options
 * @param {string} options.userDataDir isolated Canopy data directory
 * @param {string} [options.workspaceId] seeded workspace id
 * @param {string} [options.worktreeId] seeded worktree id
 * @param {string} [options.chatId] seeded root chat id
 * @param {'codex'|'claude'} [options.providerType] parent chat provider
 * @param {'completed'|'running'} [options.status] status of the root delegate
 * @param {boolean} [options.includeNestedDelegations] add a depth-2 child and
 *   depth-1 peer for Agent activity captures
 * @returns {ReturnType<typeof seedWorktreeChat> & {chatId: string}}
 */
export function seedSubagentViewerChat(options) {
  const {
    userDataDir,
    workspaceId = 'demo-ts-pnpm-vite',
    worktreeId = 'demo-main',
    chatId = SUBAGENT_VIEWER_CHAT_ID,
    providerType = 'codex',
    status = 'completed',
    includeNestedDelegations = false,
  } = options ?? {};

  if (!userDataDir) {
    throw new Error('seedSubagentViewerChat requires userDataDir');
  }
  if (!workspaceId || !worktreeId) {
    throw new Error('seedSubagentViewerChat requires a workspace and worktree');
  }

  const activeStatus = includeNestedDelegations ? 'running' : status;
  const rootBlock = delegatedBlock({
    delegationId: SUBAGENT_VIEWER_DELEGATION_IDS.root,
    agentBlockId: ROOT_BLOCK_ID,
    description: ROOT_DESCRIPTION,
    status: activeStatus,
    sequence: 1,
    depth: 1,
  });
  const parentBlocks = [
    rootBlock,
    ...spawnToolBlocks(rootBlock.delegationId, activeStatus),
  ];
  const messages = [
    {
      id: 'subagent-viewer-request',
      role: 'user',
      timestamp: TIMESTAMP,
      blocks: [
        {
          type: 'text',
          text: 'Ask a second model to review the demo parser error boundary.',
        },
      ],
    },
  ];

  if (includeNestedDelegations) {
    const peerBlock = delegatedBlock({
      delegationId: SUBAGENT_VIEWER_DELEGATION_IDS.peer,
      agentBlockId: PEER_BLOCK_ID,
      description: 'Check the demo parser tests',
      status: 'completed',
      sequence: 2,
      depth: 1,
    });
    // A watcher notification started the peer's second run.
    const peerWatcherRun = delegatedBlock({
      delegationId: SUBAGENT_VIEWER_DELEGATION_IDS.peer,
      agentBlockId: `${PEER_BLOCK_ID}-run-2`,
      description: 'Check the demo parser tests',
      status: 'running',
      sequence: 1,
      depth: 1,
      runGeneration: 2,
      prompt: subagentViewerWatcherMessage(),
    });
    const nestedBlock = delegatedBlock({
      delegationId: SUBAGENT_VIEWER_DELEGATION_IDS.nested,
      agentBlockId: NESTED_BLOCK_ID,
      description: 'Verify error context is preserved',
      status: 'running',
      sequence: 3,
      depth: 2,
      parentDelegationId: rootBlock.delegationId,
      parentDescription: rootBlock.description,
      writePaths: SUBAGENT_VIEWER_LONG_WRITE_PATHS,
    });
    parentBlocks.push(
      peerBlock,
      ...spawnToolBlocks(peerBlock.delegationId, 'completed'),
      peerWatcherRun,
    );
    messages.push(
      {
        id: 'subagent-viewer-parent-events',
        role: 'system',
        timestamp: TIMESTAMP + 100,
        blocks: parentBlocks,
      },
      ...childMessages(
        ROOT_BLOCK_ID,
        'subagent-viewer-root-child',
        TIMESTAMP + 200,
      ),
      {
        id: 'subagent-viewer-nested-spawn',
        role: 'assistant',
        timestamp: TIMESTAMP + 250,
        parentBlockId: ROOT_BLOCK_ID,
        delegationSequence: 4,
        blocks: [
          nestedBlock,
          ...spawnToolBlocks(nestedBlock.delegationId, 'running'),
        ],
      },
      ...childMessages(
        NESTED_BLOCK_ID,
        'subagent-viewer-nested-child',
        TIMESTAMP + 300,
      ),
      ...childMessages(
        PEER_BLOCK_ID,
        'subagent-viewer-peer-child',
        TIMESTAMP + 400,
      ),
    );
  } else {
    messages.push(
      {
        id: 'subagent-viewer-parent-events',
        role: 'system',
        timestamp: TIMESTAMP + 100,
        blocks: parentBlocks,
      },
      ...childMessages(
        ROOT_BLOCK_ID,
        'subagent-viewer-root-child',
        TIMESTAMP + 200,
      ),
    );
  }

  messages.push(
    {
      id: 'subagent-viewer-parent-answer',
      role: 'assistant',
      timestamp: TIMESTAMP + 600,
      blocks: [
        {
          type: 'text',
          text: `The independent review found one actionable issue: ${ERROR_FINDING}`,
        },
      ],
    },
    {
      id: 'subagent-viewer-turn-timer',
      role: 'system',
      timestamp: TIMESTAMP + 700,
      blocks: [
        {
          type: 'turn_timer',
          startedAt: TIMESTAMP,
          completedAt: TIMESTAMP + 700,
        },
      ],
    },
  );

  const seeded = seedWorktreeChat({
    userDataDir,
    workspaceId,
    worktreeId,
    providerType,
    activeTabId: chatId,
    tabs: [
      {
        id: chatId,
        title: 'Demo parser review',
        providerType,
        executionHarness: providerType,
        model: providerType === 'claude' ? 'claude-sonnet-4-6' : 'gpt-6-sol',
        messages,
      },
    ],
  });

  return { ...seeded, chatId };
}

function treeManagedBlock({
  delegationId,
  description,
  status,
  sequence,
  depth,
  parentDelegationId,
  parentDescription,
  isolated,
  writePaths = ['src/index.ts'],
}) {
  const agentBlockId = `delegated-agent-${delegationId}`;
  const revision = 'c'.repeat(40);
  return {
    type: 'delegated_agent_call',
    agentBlockId,
    delegationId,
    runGeneration: 1,
    sequence,
    outputTruncated: false,
    parentHarnessId: 'claude',
    parentTurnId: 'subagent-viewer-tree-request',
    parentToolCallId: `${delegationId}-call`,
    selectedModelId: 'sonnet',
    runtimeModelId: 'claude-sonnet-4-6',
    targetHarnessId: 'claude',
    requestedThinkingLevel: 'high',
    effectiveThinkingLevel: 'high',
    routeSnapshot: routeSnapshot(),
    status,
    approvalPending: false,
    description,
    prompt: `Review src/index.ts for ${description.toLowerCase()}.`,
    executionMode: 'background',
    permissions: { writePaths },
    ...(isolated
      ? { isolatedWorkspace: { revision, dirtyParentChangesIncluded: false } }
      : {
          workspaceObservation: {
            consistency: 'live_shared_worktree',
            headRevision: 'a'.repeat(40),
            dirty: false,
            observedAt: TIMESTAMP + sequence * 100,
          },
        }),
    depth,
    ...(parentDelegationId ? { parentDelegationId, parentDescription } : {}),
    usage: { inputTokens: 420, outputTokens: 120 },
    ...(status === 'completed'
      ? { finalText: `${description} is complete.` }
      : {}),
    ...(status === 'failed'
      ? {
          error: {
            code: 'runtime_error',
            message: 'The seeded delegate could not complete its review.',
            retryable: false,
          },
        }
      : {}),
    createdAt: TIMESTAMP + sequence * 100,
  };
}

