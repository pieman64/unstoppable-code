function delegatedBlock({
  delegationId,
  agentBlockId,
  description,
  status,
  sequence,
  depth,
  parentDelegationId,
  parentDescription,
  runGeneration = 1,
  prompt,
  writePaths = ['src/index.ts'],
}) {
  return {
    type: 'delegated_agent_call',
    agentBlockId,
    delegationId,
    runGeneration,
    sequence,
    outputTruncated: false,
    parentHarnessId: 'codex',
    parentTurnId: 'subagent-viewer-request',
    parentToolCallId: `${delegationId}-call`,
    selectedModelId: 'sonnet',
    runtimeModelId: 'claude-sonnet-4-6',
    targetHarnessId: 'claude',
    requestedThinkingLevel: 'high',
    effectiveThinkingLevel: 'high',
    routeSnapshot: routeSnapshot(),
    status,
    approvalPending: false,
    description,
    prompt: prompt ?? `Inspect src/index.ts and ${description.toLowerCase()}.`,
    executionMode: 'background',
    permissions: { writePaths },
    workspaceObservation: {
      consistency: 'live_shared_worktree',
      headRevision: 'a'.repeat(40),
      dirty: false,
      observedAt: TIMESTAMP + sequence * 100,
    },
    depth,
    ...(parentDelegationId ? { parentDelegationId } : {}),
    ...(parentDescription ? { parentDescription } : {}),
    usage: { inputTokens: 420, outputTokens: 120 },
    ...(status === 'completed' ? { finalText: ERROR_FINDING } : {}),
    createdAt: TIMESTAMP + sequence * 100,
  };
}

function spawnToolBlocks(delegationId, status) {
  const toolUseId = `${delegationId}-call`;
  return [
    {
      type: 'tool_use',
      toolUseId,
      toolName: 'canopy_spawn_delegate',
      input: JSON.stringify({
        model: 'sonnet',
        task_name: delegationId,
        message: `Review ${delegationId} in the demo parser.`,
        execution_mode: 'background',
        reasoning_effort: 'high',
      }),
    },
    {
      type: 'tool_result',
      toolUseId,
      toolName: 'canopy_spawn_delegate',
      output: JSON.stringify({
        ok: true,
        value: {
          delegationId,
          status,
          approvalPending: false,
          routeSnapshot: {
            selectedModelId: 'sonnet',
            runtimeModelId: 'claude-sonnet-4-6',
            harnessId: 'claude',
            effectiveThinkingLevel: 'high',
          },
          workspaceObservation: {
            consistency: 'live_shared_worktree',
            headRevision: 'a'.repeat(40),
            dirty: false,
            observedAt: TIMESTAMP + 100,
          },
          outputTruncated: false,
          ...(status === 'completed' ? { finalText: ERROR_FINDING } : {}),
        },
      }),
      isError: false,
    },
  ];
}

