/**
 * Seed a three-managed-level tree plus native Claude history. Callers seed the
 * demo worktree first. Terminal nodes are backed by durable records for the
 * root picker and isolated-worktree disclosure. Live child/grandchild nodes
 * are transcript blocks only: broker recovery correctly settles retained live
 * records on startup, while these root transcript observations remain running.
 *
 * @param {object} options
 * @param {string} options.userDataDir isolated CANOPY_DATA_DIR
 * @param {string} [options.workspaceId] seeded workspace id
 * @param {string} [options.worktreeId] seeded worktree id
 * @param {string} [options.chatId] seeded root chat id
 * @param {'workspaces' | 'app-workspaces'} [options.storageRoot] data-dir
 *   folder the workspace lives in; App Advisor needs `app-workspaces`
 * @returns {ReturnType<typeof seedWorktreeChat> & {chatId: string}}
 */
export function seedSubagentViewerTreeChat(options) {
  const {
    userDataDir,
    workspaceId = 'demo-ts-pnpm-vite',
    worktreeId = 'demo-main',
    chatId = SUBAGENT_VIEWER_CHAT_ID,
    storageRoot = 'workspaces',
  } = options ?? {};
  if (!userDataDir) {
    throw new Error('seedSubagentViewerTreeChat requires userDataDir');
  }
  if (!workspaceId || !worktreeId || !chatId) {
    throw new Error('seedSubagentViewerTreeChat requires a root chat scope');
  }

  const nodeDefinitions = [
    {
      delegationId: SUBAGENT_VIEWER_TREE_IDS.idleParent,
      description: SUBAGENT_VIEWER_TREE_TITLES.idleParent,
      status: 'completed',
      sequence: 1,
      depth: 1,
    },
    {
      delegationId: SUBAGENT_VIEWER_TREE_IDS.liveChild,
      description: SUBAGENT_VIEWER_TREE_TITLES.liveChild,
      status: 'running',
      sequence: 2,
      depth: 2,
      parentDelegationId: SUBAGENT_VIEWER_TREE_IDS.idleParent,
      parentDescription: 'Finished parser review',
    },
    {
      delegationId: SUBAGENT_VIEWER_TREE_IDS.liveGrandchild,
      description: SUBAGENT_VIEWER_TREE_TITLES.liveGrandchild,
      status: 'running',
      sequence: 3,
      depth: 3,
      parentDelegationId: SUBAGENT_VIEWER_TREE_IDS.liveChild,
      parentDescription: 'Live parser cause check',
      writePaths: SUBAGENT_VIEWER_LONG_WRITE_PATHS,
    },
    {
      delegationId: SUBAGENT_VIEWER_TREE_IDS.failed,
      description: SUBAGENT_VIEWER_TREE_TITLES.failed,
      status: 'failed',
      sequence: 4,
      depth: 1,
      // A watcher notification started run 2 and a user follow-up run 3.
      earlierRuns: [
        {
          prompt: `Review src/index.ts for ${SUBAGENT_VIEWER_TREE_TITLES.failed.toLowerCase()}.`,
          text: SUBAGENT_VIEWER_FAILED_RUN_TEXT.first,
        },
        {
          prompt: subagentViewerWatcherMessage(),
          text: SUBAGENT_VIEWER_FAILED_RUN_TEXT.watcher,
        },
      ],
      prompt: SUBAGENT_VIEWER_FAILED_RUN_TEXT.followUp,
      userFollowUp: true,
    },
    {
      delegationId: SUBAGENT_VIEWER_TREE_IDS.isolated,
      description: SUBAGENT_VIEWER_TREE_TITLES.isolated,
      status: 'completed',
      sequence: 5,
      depth: 1,
      isolated: true,
    },
  ];
  const rootBlocks = nodeDefinitions
    .filter((node) => node.depth === 1)
    .map(treeManagedBlock);
  // Child spawns live in their parent's child stream (parentBlockId), matching
  // the transcript input's identity index and preserving links to the record-
  // backed completed parent without creating a retained live run to recover.
  const nestedMessages = nodeDefinitions
    .filter((node) => node.depth > 1)
    .map((node) => {
      const block = treeManagedBlock(node);
      const parentBlockId = `delegated-agent-${node.parentDelegationId}`;
      return {
        id: `subagent-viewer-tree-${node.delegationId}`,
        role: 'assistant',
        timestamp: TIMESTAMP + node.sequence * 100,
        parentBlockId,
        delegationSequence: node.sequence,
        blocks: [block],
      };
    });
  const messages = [
    {
      id: 'subagent-viewer-tree-request',
      role: 'user',
      timestamp: TIMESTAMP,
      blocks: [
        {
          type: 'text',
          text: 'Review the demo parser with a mixed set of seeded subagents.',
        },
      ],
    },
    {
      id: 'subagent-viewer-tree-managed-events',
      role: 'system',
      timestamp: TIMESTAMP + 100,
      blocks: rootBlocks,
    },
    ...nestedMessages,
    ...nativeTreeMessages(),
    ...childMessages(
      `delegated-agent-${SUBAGENT_VIEWER_TREE_IDS.liveChild}`,
      'subagent-viewer-tree-live-child',
      TIMESTAMP + 300,
    ),
    ...childMessages(
      `delegated-agent-${SUBAGENT_VIEWER_TREE_IDS.liveGrandchild}`,
      'subagent-viewer-tree-live-grandchild',
      TIMESTAMP + 500,
    ),
    {
      id: 'subagent-viewer-tree-parent-answer',
      role: 'assistant',
      timestamp: TIMESTAMP + 700,
      blocks: [
        {
          type: 'text',
          text: 'The seeded tree preserves separate managed and native activity.',
        },
      ],
    },
    {
      id: 'subagent-viewer-tree-turn-timer',
      role: 'system',
      timestamp: TIMESTAMP + 800,
      blocks: [
        {
          type: 'turn_timer',
          startedAt: TIMESTAMP,
          completedAt: TIMESTAMP + 800,
        },
      ],
    },
  ];
  let seeded = seedWorktreeChat({
    userDataDir,
    workspaceId,
    worktreeId,
    providerType: 'claude',
    activeTabId: chatId,
    tabs: [
      {
        id: chatId,
        title: 'Demo parser subagent tree',
        providerType: 'claude',
        executionHarness: 'claude',
        model: 'sonnet',
        messages,
      },
    ],
  });
  if (storageRoot !== 'workspaces') {
    // `seedWorktreeChat` always writes under `workspaces/` and is byte-pinned
    // by the performance harness, so move its file to the requested root.
    const filePath = path.join(
      userDataDir,
      storageRoot,
      workspaceId,
      'chats',
      `${worktreeId}.json`,
    );
    writeJson(filePath, seeded.file);
    rmSync(seeded.filePath);
    seeded = { ...seeded, filePath };
  }
  seedSubagentViewerManagedRecords({
    userDataDir,
    workspaceId,
    worktreeId,
    chatId,
    storageRoot,
    nodes: nodeDefinitions.filter(
      (node) => node.status === 'failed' || node.isolated === true,
    ),
  });
  return { ...seeded, chatId };
}
