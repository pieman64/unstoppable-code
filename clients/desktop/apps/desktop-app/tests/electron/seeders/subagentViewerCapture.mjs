/** A fake watcher notification as a delegate receives it: hidden context only. */
export function subagentViewerWatcherMessage() {
  return [
    '<system_instruction>',
    'Canopy watcher internal event details. This message was generated by Canopy, not typed by the user.',
    '',
    '<canopy_watcher_event>',
    JSON.stringify(
      {
        watcherId: 'subagent-viewer-watcher',
        label: SUBAGENT_VIEWER_FAILED_RUN_TEXT.watcherLabel,
        trigger: 'managed_delegation_completion',
        target: { kind: 'managed_delegation', outcome: 'completed' },
      },
      null,
      2,
    ),
    '</canopy_watcher_event>',
    '</system_instruction>',
  ].join('\n');
}

