/** CAN-2960 rollout boundary inventory. Paths are repository-relative.
 * Keep known missing gates here: an audit must fail until they are resolved or
 * explicitly accepted in the rollout plan. Recovery routes deliberately use
 * growth:false; helper presence does not prove those operations are disabled.
 */
export type OrgProjectsFlagGateKind =
  /** The module itself evaluates `gate` at runtime. */
  | 'direct'
  /** The module is reachable only through `host`, which evaluates `gate`. */
  | 'host'
  /** Intentionally outside the rollout flag; `reason` records the decision. */
  | 'exception';

export interface OrgProjectsFlagGate {
  readonly ticket: string;
  readonly file: string;
  readonly entryPoint: string;
  readonly gate: string;
  readonly kind: OrgProjectsFlagGateKind;
  /** Repository-relative host module for `kind: 'host'`. */
  readonly host?: string;
  /** Accepted-exception rationale for `kind: 'exception'`. */
  readonly reason?: string;
}

