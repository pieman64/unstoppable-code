// File-extension and exact-filename mapping derived from VS Code's default
// Seti file icon theme.
// Source: https://github.com/microsoft/vscode/blob/main/extensions/theme-seti/icons/vs-seti-icon-theme.json
// License: MIT
//
// Notes on adaptation:
//   * VS Code's icon ids are prefixed with `_` (eg. `_typescript`); we strip
//     that prefix so ids align with the SVG filenames in
//     jesseweed/seti-ui (eg. `typescript`).
//   * VS Code uses `_<name>_N` numeric suffixes purely as font-color variants
//     of the same silhouette. We collapse them onto the base icon since the
//     SVGs we ship already include the correct fill colors.
//   * VS Code also has a `light` variant per icon (different font color for
//     light themes). The Seti SVGs ship a single colored variant which works
//     well on both light and dark backgrounds, so we don't track `light`.
//
// To add a new mapping:
//   1. Make sure the icon name exists in `./icon-registry.ts`.
//   2. Add the extension or filename below pointing at that icon name.
//   3. Use lowercase keys; the resolver lowercases the input filename.

