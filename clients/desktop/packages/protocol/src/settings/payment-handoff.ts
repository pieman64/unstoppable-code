import { z } from 'zod';
import {
  BILLING_PAYMENT_MODALS,
  type BillingPaymentModalIntent,
  type SettingsPaymentOwner,
} from '../billing/payment-intent';
import {
  isPaidBillingPlanKey,
  type PaidBillingPlanKey,
} from '../billing/plan-keys';
import {
  BILLING_TOP_UP_MAX_USD,
  BILLING_TOP_UP_MIN_USD,
} from '../billing/top-up-intent';
import { settingsRouteIdSchema } from './routes';

export type { SettingsPaymentOwner };

export const settingsPaymentOwnerSchema = z.union([
  z.strictObject({ kind: z.literal('personal') }),
  z.strictObject({
    kind: z.literal('organization'),
    organizationId: settingsRouteIdSchema,
  }),
]);

/**
 * What a desktop payment CTA asks the browser to open. The request id is
 * generated by the host that opens the browser, never by the caller, and a
 * handoff never carries an amount that would be charged without the web
 * page's own confirmation.
 */
export const settingsPaymentHandoffIntentSchema = z
  .union([
    z.strictObject({
      kind: z.literal('top-up'),
      reason: z.enum(['credits', 'unlock_models']),
      amountUsd: z
        .number()
        .min(BILLING_TOP_UP_MIN_USD)
        .max(BILLING_TOP_UP_MAX_USD)
        .optional(),
    }),
    z.strictObject({
      kind: z.literal('modal'),
      modal: z.enum(BILLING_PAYMENT_MODALS),
      plan: z
        .custom<PaidBillingPlanKey>((value) => isPaidBillingPlanKey(value))
        .optional(),
    }),
  ])
  .superRefine((intent, ctx) => {
    if (
      intent.kind === 'modal' &&
      intent.plan !== undefined &&
      intent.modal !== 'subscription'
    )
      ctx.addIssue({
        code: 'custom',
        path: ['plan'],
        message: 'plan is only valid on the subscription modal',
      });
  });

export type SettingsPaymentHandoffIntent = z.infer<
  typeof settingsPaymentHandoffIntentSchema
>;

export const settingsPaymentHandoffRequestSchema = z.strictObject({
  owner: settingsPaymentOwnerSchema,
  intent: settingsPaymentHandoffIntentSchema,
});

export type SettingsPaymentHandoffRequest = z.infer<
  typeof settingsPaymentHandoffRequestSchema
>;

/**
 * Why a handoff did not open an authenticated payment page. Hosts never
 * report an unauthenticated fallback as success.
 *
 * - `unavailable`: the handoff is off (flag off or no captured credentials).
 * - `forbidden`: the owner is not in the viewer's current membership.
 * - `identity_changed`: the account changed before the browser opened.
 * - `browser_failed`: the authenticated link was created but the browser did
 *   not open.
 * - `failed`: the authenticated link could not be created.
 */
export const SETTINGS_PAYMENT_HANDOFF_FAILURES = [
  'unavailable',
  'forbidden',
  'identity_changed',
  'browser_failed',
  'failed',
] as const;

export type SettingsPaymentHandoffFailure =
  (typeof SETTINGS_PAYMENT_HANDOFF_FAILURES)[number];

export const settingsPaymentHandoffResultSchema = z.union([
  z.strictObject({ ok: z.literal(true) }),
  z.strictObject({
    ok: z.literal(false),
    reason: z.enum(SETTINGS_PAYMENT_HANDOFF_FAILURES),
  }),
]);

export type SettingsPaymentHandoffResult = z.infer<
  typeof settingsPaymentHandoffResultSchema
>;

export const settingsPaymentHandoffAvailabilitySchema = z.strictObject({
  available: z.boolean(),
});

export type SettingsPaymentHandoffAvailability = z.infer<
  typeof settingsPaymentHandoffAvailabilitySchema
>;

/** The web modal intent a validated handoff opens, given a fresh request id. */
export function paymentModalIntentForHandoff(
  intent: Extract<SettingsPaymentHandoffIntent, { kind: 'modal' }>,
  requestId: string,
): BillingPaymentModalIntent {
  if (intent.modal === 'subscription')
    return intent.plan === undefined
      ? { modal: 'subscription', requestId }
      : { modal: 'subscription', requestId, plan: intent.plan };
  return { modal: intent.modal, requestId };
}
